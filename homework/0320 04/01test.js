/* 判斷成績是否及格 */ // 這是一段註解，用來說明下面的程式功能是「判斷分數有沒有及格」

let score = 75; // 宣告一個變數 score，並把分數設定為 75

if (score >= 60) { // 判斷 score 是否大於或等於 60，如果是，就代表及格
    console.log("及格"); // 如果條件成立，就在主控台印出「及格」
} else { // 如果上面的條件不成立，也就是 score 小於 60，就會執行這裡
    console.log("不及格"); // 如果條件不成立，就在主控台印出「不及格」
} // if else 判斷結束