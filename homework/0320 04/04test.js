/* 用 for 算 1 到 100 的總和 */ // 這是一段註解，說明這個程式會用 for 迴圈計算 1 到 100 加起來的總和

let sum = 0; // 宣告一個變數 sum，用來存放總和，一開始先設定為 0

for (let i = 1; i <= 100; i++) { // 建立 for 迴圈：i 從 1 開始，只要 i 小於等於 100，就一直重複執行，每次結束後 i 加 1
    sum = sum + i; // 把目前的 i 加進 sum 裡，讓 sum 慢慢累加
} // for 迴圈結束

console.log("總和是：" + sum); // 在主控台輸出文字「總和是：」加上最後算好的 sum