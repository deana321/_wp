/* 用 array 陣列儲存多個成績 */ // 這是一段註解，說明這個程式會用陣列儲存多個成績

let scores = [80, 90, 70, 60, 100]; // 宣告一個陣列 scores，裡面放了 5 個成績資料

console.log("第一個成績：" + scores[0]); // 輸出陣列中的第一個成績，scores[0] 代表第 1 個資料，也就是 80
console.log("第二個成績：" + scores[1]); // 輸出陣列中的第二個成績，scores[1] 代表第 2 個資料，也就是 90
console.log("陣列長度：" + scores.length); // 輸出陣列的長度，scores.length 代表陣列裡有幾個資料，這裡是 5